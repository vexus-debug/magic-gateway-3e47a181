function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en" suppressHydrationWarning>
      <head>
        <script
          dangerouslySetInnerHTML={{
            __html: `try{var a=localStorage.getItem("clinexus-dashboard-appearance");if(a==="dark"||(!a&&matchMedia("(prefers-color-scheme: dark)").matches))document.documentElement.classList.add("dashboard-dark")}catch(e){}`,
          }}
        />
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  useEffect(() => { console.log("MOUNT RootComponent", performance.now()); return () => console.log("UNMOUNT RootComponent", performance.now()); }, []);

  return (
    <QueryClientProvider client={queryClient}>
      {/* The imported app owns its own routing and is mounted once here, so it
          is never unmounted/remounted when the URL changes (that caused a blank
          flash on every navigation). */}
      <LegacyAppHost />
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
    </QueryClientProvider>
  );
}
